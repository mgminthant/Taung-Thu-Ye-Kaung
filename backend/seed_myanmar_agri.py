def seed_sqlite() -> tuple[int, int]:
    """Insert-if-missing into web/dev.db. Returns (created, skipped)."""
    if not DB_PATH.exists():
        raise SystemExit(f"SQLite DB not found: {DB_PATH}")

    conn = sqlite3.connect(str(DB_PATH))
    created = skipped = 0
    try:
        for art in ARTICLES:
            exists = conn.execute(
                "SELECT 1 FROM Article WHERE id = ?", (art["id"],)
            ).fetchone()
            if exists:
                skipped += 1
                continue

            conn.execute(
                """INSERT INTO Article
                   (id, title, category, crop, content, source, tags,
                    region, language, verified, createdAt, updatedAt)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, datetime('now'), datetime('now'))""",
                (
                    art["id"],
                    art["title"],
                    art["category"],
                    art["crop"],
                    art["content"],
                    SOURCE,
                    art["tags"],
                    REGION,
                    LANGUAGE,
                    VERIFIED,
                ),
            )
            # Relation tables mirror the legacy single-value columns.
            conn.execute(
                "INSERT OR IGNORE INTO ArticleCategory (articleId, category) VALUES (?, ?)",
                (art["id"], art["category"]),
            )
            conn.execute(
                "INSERT OR IGNORE INTO ArticleCrop (articleId, crop) VALUES (?, ?)",
                (art["id"], art["crop"]),
            )
            created += 1
        conn.commit()
    finally:
        conn.close()
    return created, skipped


def rebuild_chroma() -> int:
    """Full re-index using the backend's own loader + VectorStore."""
    sys.path.insert(0, str(BACKEND_DIR))

    from app.config import settings
    from app.sqlite_loader import load_knowledge_from_sqlite
    from app.vectorstore import VectorStore

    records = load_knowledge_from_sqlite()
    print(f"[chroma] loaded {len(records)} records from {DB_PATH}")
    store = VectorStore(
        persist_dir=settings.vector_store_path,
        embedding_model=settings.embedding_model,
    )
    store.ensure_indexed(records)
    count = store._get_collection().count()
    print(f"[chroma] collection '{store._collection_name()}' now holds {count} vectors")
    return count


def main() -> None:
    created, skipped = seed_sqlite()
    total_rows = sqlite3.connect(str(DB_PATH)).execute(
        "SELECT COUNT(*) FROM Article"
    ).fetchone()[0]
    print(f"[sqlite] {created} inserted, {skipped} already present ({total_rows} total)")

    chroma_count = rebuild_chroma()

    if chroma_count == total_rows:
        print(f"OK: SQLite ({total_rows}) and Chroma ({chroma_count}) are in sync")
    else:
        raise SystemExit(
            f"MISMATCH: sqlite={total_rows} chroma={chroma_count}"
        )


if __name__ == "__main__":
    main()
